"use strict";
const assert = require("node:assert/strict");
global.window=global;
require("../housing-strategy-model.js");
const m=global.HousingStrategyModel;
assert.ok(m && typeof m.compare === "function");
const res=m.compare({},m.PRESETS.baseline,45000);
assert.deepEqual(res.map(x=>x.kind),["rent","apartment","wait","existing","modular"]);
for(const a of res){
  assert.equal(a.valid,true,a.reason);
  assert.ok(Number.isFinite(a.nominal));
  assert.ok(Number.isFinite(a.real));
}
assert.ok(Math.abs(m.loanPayment(12000,0,120)-100)<0.001);
assert.ok(m.evaluate("rent",{},m.PRESETS.baseline,5000).valid === false);
assert.ok(m.evaluate("apartment",{},m.PRESETS.baseline,10000).valid === false);
const noInfl={...m.PRESETS.baseline, inflation:0, domesticReturn:0, overseasReturn:0, fxDepreciation:0, rentRise:0};
const noCosts={...m.BASE, rentDeposit:0, rentMonthly:0, rentOther:0, monthlyBudget:100, years:1, overseasShare:0};
const rent=m.evaluate("rent",noCosts,noInfl,1000);
assert.equal(rent.valid,true);
assert.ok(Math.abs(rent.nominal-(1000+12*100))<0.001);
assert.ok(Math.abs(rent.real-rent.nominal)<0.001);
const fx0=m.evaluate("rent",{...m.BASE,overseasShare:100}, {...m.PRESETS.baseline,fxDepreciation:0},45000);
const fx10=m.evaluate("rent",{...m.BASE,overseasShare:100}, {...m.PRESETS.baseline,fxDepreciation:10},45000);
assert.ok(fx10.nominal>fx0.nominal);
const comp=m.evaluate("apartment",{...m.BASE,monthlyBudget:0},m.PRESETS.baseline,45000);
assert.ok(comp.monthlyBudgetExceeded>0);
const waitFail=m.evaluate("wait",{...m.BASE,apartmentPrice:300000},m.PRESETS.baseline,45000);
assert.equal(waitFail.valid,false);
const abs=m.compare(m.BASE,m.PRESETS.energy,45000);
assert.equal(abs.length,5);
const mock={innerHTML:""};
global.document={getElementById:(key)=>key==="housingStrategy"?mock:null};
global.state={deadline:"2028-11-22",strategy:{}};
global.plan=()=>({equity:45000});
global.save=()=>{};
require("../housing-strategy.js");
assert.match(mock.innerHTML,/월세 유지/);
assert.match(mock.innerHTML,/모듈러/);
global.housingStrategySet("base","monthlyBudget","500");
assert.equal(global.state.strategy.monthlyBudget,500);
global.housingStrategyPreset("currency");
assert.equal(global.state.strategyScenario,"currency");
assert.match(mock.innerHTML,/고물가·원화 약세/);
global.housingStrategySet("macro","fxDepreciation","9");
assert.equal(global.state.strategyOverrides.currency.fxDepreciation,9);
console.log("Housing strategy model and UI integration: all tests passed");
